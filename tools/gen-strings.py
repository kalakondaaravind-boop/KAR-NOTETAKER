#!/usr/bin/env python3
"""Generates app/src/main/res/values/strings.xml from tools/strings_source.py and checks that every
R.string / R.plurals / @string reference in the app exists (and that no defined string is unused)."""
import glob, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from strings_source import S, P

def esc(t):
    t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    t = t.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if t.startswith("@") or t.startswith("?"):
        t = "\\" + t
    return t

src = "".join(open(f, encoding="utf-8").read() for f in glob.glob(str(ROOT / "app/src/main/kotlin/**/*.kt"), recursive=True))
res = "".join(open(f, encoding="utf-8").read() for f in glob.glob(str(ROOT / "app/src/main/res/**/*.xml"), recursive=True) if "values/strings.xml" not in f)
res += open(ROOT / "app/src/main/AndroidManifest.xml", encoding="utf-8").read()
used = set(re.findall(r"R\.string\.([a-z0-9_]+)", src)) | set(re.findall(r"@string/([a-z0-9_]+)", res))
used_p = set(re.findall(r"R\.plurals\.([a-z0-9_]+)", src))
missing = sorted(used - S.keys()); missing_p = sorted(used_p - P.keys())
unused = sorted(S.keys() - used)
ok = True
if missing: print("MISSING strings:", missing); ok = False
if missing_p: print("MISSING plurals:", missing_p); ok = False
if unused: print("unused strings (kept):", unused)
for k, v in S.items():
    if re.search(r"%(?!\d\$[sd])", v.replace("%%", "")): print("bad format in", k, v); ok = False
out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen-strings.py from tools/strings_source.py. Edit the source, not this file. -->", "<resources>"]
for k in sorted(S):
    fmt = "" if re.search(r"%\d\$", S[k]) else ' formatted="false"' if "%" in S[k] else ""
    out.append(f'    <string name="{k}"{fmt}>{esc(S[k])}</string>')
for k in sorted(P):
    out.append(f'    <plurals name="{k}">')
    for q, v in P[k].items(): out.append(f'        <item quantity="{q}">{esc(v)}</item>')
    out.append("    </plurals>")
out.append("</resources>")
(ROOT / "app/src/main/res/values/strings.xml").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {len(S)} strings, {len(P)} plurals")
sys.exit(0 if ok else 1)
